def make_table(story, header, rows, ratios, caption=None, align_map=None, repeat=True):
    """header: list[str]; rows: list[list[str]]; ratios sum to 1."""
    widths = [r * AVAIL for r in ratios]
    data = [[Paragraph(f"<b>{h}</b>", S["cellH"]) for h in header]]
    for row in rows:
        cells = []
        for j, v in enumerate(row):
            st = S["cell"] if (align_map or {}).get(j, "L") == "L" else S["cellC"]
            cells.append(Paragraph(str(v), st))
        data.append(cells)
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1 if repeat else 0)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 3.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 10))
    if caption and len(rows) <= 12:
        story.append(KeepTogether([t, Spacer(1, 4), Paragraph(caption, S["caption"])]))
    else:
        story.append(t)
        if caption:
            story.append(Spacer(1, 4))
            story.append(Paragraph(caption, S["caption"]))
    story.append(Spacer(1, 10))

def arabic(text):
    import arabic_reshaper
    from bidi.algorithm import get_display
    return get_display(arabic_reshaper.reshape(text))

