         "tracks, paths and footways (250 m), minor roads and forest tracks (350 m), major "
         "roads for power-line and roadside ignitions (200 m), and settlements for field-edge "
         "cooking (400 m). The maximum of the five weighted decays forms the ignition layer. "
         "The same layer, inverted, provides the remoteness measure the siting rules demand: "
         "distance to the nearest motorable road, used to give priority to hard-to-reach "
